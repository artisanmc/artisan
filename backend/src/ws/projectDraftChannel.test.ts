import { afterEach, expect, test } from "bun:test";
import { db } from "../db";
import { networks, serverKeys } from "../db/schema";
import { generateServerKey } from "../lib/auth";
import { connToServerId, cleanupConn, handlePluginMessage, registerConn, requestProjectDraft, supportsProjectDrafts } from "./hub";

afterEach(() => { cleanupConn("draft-channel"); cleanupConn("draft-attacker"); });
test("draft channel negotiates capability and rejects replies from another connection", async () => {
  await db.delete(networks);
  const now = new Date();
  await db.insert(networks).values({ id: "draft-wire", name: "N", createdAt: now, updatedAt: now });
  const key = await generateServerKey();
  await db.insert(serverKeys).values({ id: key.id, hash: key.hash, networkId: "draft-wire", createdAt: now });
  const messages: any[] = [];
  registerConn("draft-channel", (raw) => messages.push(JSON.parse(raw)));
  await handlePluginMessage("draft-channel", JSON.stringify({ type: "hello", server_key: key.key, plugin_version: "test", minecraft_version: "1.21.4", current_bundle_hash: "", local_project_ids: [], capabilities: ["project_drafts_v1"] }));
  expect(supportsProjectDrafts(key.id)).toBe(true);
  const promise = requestProjectDraft(key.id, { project_id: "folder", owner_id: "owner", action: "update", draft_id: "d", expected_revision: 2, operation_id: "op", name: "Draft", snapshot: { baseline: {}, tree: {}, at: 0 } }, 1000);
  for (let i = 0; i < 50 && !messages.some((message) => message.type === "project_draft_request"); i++) await new Promise((resolve) => setTimeout(resolve, 10));
  const request = messages.find((message) => message.type === "project_draft_request");
  expect(request).toMatchObject({ project_id: "folder", owner_id: "owner", action: "update", operation_id: "op", expected_revision: 2 });
  connToServerId.set("draft-attacker", "other-server");
  let settled = false;
  void promise.then(() => { settled = true; });
  await handlePluginMessage("draft-attacker", JSON.stringify({ type: "project_draft_result", request_id: request.request_id, ok: true }));
  expect(settled).toBe(false);
  await handlePluginMessage("draft-channel", JSON.stringify({ type: "project_draft_result", request_id: request.request_id, ok: false, error: "draft_conflict" }));
  expect(await promise).toMatchObject({ kind: "result", result: { ok: false, error: "draft_conflict" } });
  const interrupted = requestProjectDraft(key.id, { project_id: "folder", owner_id: "owner", action: "list" });
  cleanupConn("draft-channel");
  expect(await interrupted).toEqual({ kind: "offline" });
  expect(supportsProjectDrafts(key.id)).toBe(false);
});
