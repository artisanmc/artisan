import {readFile,writeFile} from 'node:fs/promises';
import {db} from '../src/db';
import {networks,memberships,serverKeys} from '../src/db/schema';
import {generateServerKey} from '../src/lib/auth';
const path=new URL('../.phase5-local-state.json',import.meta.url);
const s=JSON.parse(await readFile(path,'utf8'));
if(s.isolated) throw Error('Already configured');
const n=`${s.id}_isolated`,now=new Date(),key=await generateServerKey();
await db.insert(networks).values({id:n,name:'Phase 5 isolated runtime',slug:n,createdAt:now,updatedAt:now});
await db.insert(memberships).values({id:n,userId:s.id,networkId:n,role:'owner',createdAt:now});
await db.insert(serverKeys).values({id:key.id,hash:key.hash,label:'Phase 5 isolated runtime',slug:'runtime',networkId:n,createdAt:now});
s.isolated={networkId:n,serverId:key.id}; await writeFile(path,JSON.stringify(s),{mode:0o600});
await writeFile('../.scratch/phase5-integration-20260913/minecraft/plugins/Artisan/config.yml',`server_key: "${key.key}"\nws_url: "ws://artisan-backend-1:3001/ws/plugin"\nlanguage: en\nresource-pack:\n  enabled: true\n  send-on-join: true\n  send-delay-ticks: 20\n`,{mode:0o600});
await writeFile('../.scratch/phase5-integration-20260913/minecraft/eula.txt','eula=true\n');
await writeFile('../.scratch/phase5-integration-20260913/minecraft/server.properties','online-mode=false\nserver-port=25565\nlevel-type=minecraft:flat\ngenerate-structures=false\nspawn-protection=0\nview-distance=2\nsimulation-distance=2\nenable-rcon=true\nrcon.password=fixture-local-only\nrcon.port=25575\n');
console.log('Isolated runtime fixture configured');process.exit(0);
