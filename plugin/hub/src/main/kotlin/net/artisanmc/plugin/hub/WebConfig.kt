package net.artisanmc.plugin.hub

/**
 * The `web` section of environment.yml. Empty [bind]: every interface. Empty [url]: sign-in
 * links target the address the player joined the server with.
 */
data class WebConfig(
    val enabled: Boolean = true,
    val port: Int = 8765,
    val bind: String = "",
    val url: String = "",
    /** [HUB] serves the editor; [LEAF] connects through [hubUrl] to another server's hub. */
    val role: String = HUB,
    /** The server's name in the network; empty: its folder name. */
    val name: String = "",
    val hubUrl: String = "",
    /** The network's shared secret; empty: Velocity's, else a secret generated by the hub. */
    val secret: String = "",
) {
    val leaf: Boolean get() = role == LEAF

    companion object {
        const val HUB = "hub"
        const val LEAF = "leaf"
    }
}
