package net.artisanmc.plugin.hub

/**
 * The `web` section of environment.yml. Empty [bind]: every interface. Empty [url]: sign-in
 * links target the address the player joined the server with.
 */
data class WebConfig(
    val enabled: Boolean = true,
    val port: Int = 8765,
    val bind: String = "",
    val url: String = "",
    /** The server's name in the network; empty: its folder name. */
    val name: String = "",
    /** The hub's plugin WebSocket; empty: this server is the hub and serves the editor. */
    val hubUrl: String = "",
    /** The network's shared secret; empty: Velocity's, else a secret generated by the hub. */
    val secret: String = "",
    /** Days an editor session stays open without a request. */
    val sessionDays: Int = 7,
    /**
     * The tunnel server this hub opens a tunnel to (ADR `editor-tunnel`); empty: none. Unused
     * when [url] is set: the editor is then reached directly.
     */
    val tunnel: String = "",
    /** The code a private tunnel server asks for; empty: none. */
    val tunnelAccess: String = "",
    /**
     * Artisan's pack host ([PackCdn]): the hub uploads each pack there, players download it from
     * there rather than from [url] or the server's port. Empty: none.
     */
    val packCdn: String = "",
    /**
     * The MCP endpoint `/mcp` and its OAuth sign-in (ADR `mcp-server`): AI clients (Claude,
     * ChatGPT…) write drafts for a player who approved them. Off unless set.
     */
    val mcp: Boolean = false,
    /** The editor's assistant on the admin's model and key (ADR `editor-assistant`): the `ai` section. */
    val ai: AiConfig = AiConfig(),
) {
    val leaf: Boolean get() = hubUrl.isNotBlank()

    companion object {
        /** `web.tunnel` when environment.yml does not set it: no port to open by default. */
        const val DEFAULT_TUNNEL = "connect.artisanmc.app"
        /** Replaces [DEFAULT_TUNNEL] when set: the Gradle tests set it empty, so no test opens a real tunnel. */
        const val TUNNEL_PROPERTY = "artisan.web.tunnel"
    }
}
