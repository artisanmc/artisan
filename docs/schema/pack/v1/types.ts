/**
 * Artisan — Pack schema v1 — TypeScript types
 *
 * Manifest of an Artisan pack. Lives at the root of an .itfz archive (zip)
 * that contains the manifest + menus + templates + commands + translations + referenced assets.
 *
 * Concepts:
 *   - Pack    = organization unit in the workspace + shareable export format.
 *   - Bundle  = signed runtime artifact (config + resource pack) consumed by the plugin.
 *               Different concept, do not confuse the two.
 */

export interface PackManifest {
  /** Locked to allow migrations. */
  schema: "pack/v1";
  /** Pack slug. Lowercase + alphanumeric + hyphens/underscores. */
  id: string;
  /** Name shown in the dashboard and the marketplace. */
  name: string;
  /** Short description for the marketplace and import. */
  description?: string;
  /** Semver version (X.Y.Z). Bumped on each export. */
  version: string;
  /** Author name. In V3 marketplace, tied to a verified account. */
  author?: string;
  /** SPDX license (MIT, CC-BY-NC-4.0, etc.). */
  license?: string;
  /** Optional presentation URL. */
  homepage?: string;
  /** Tags for categorization and search. */
  tags?: string[];
  /** Minimum Artisan version required. */
  artisan_min_version?: string;
  /** Relative path of a preview image in the archive. */
  preview_image?: string;
  /** Ids of included menus. Each must have menus/<id>.json in the archive. */
  menus?: string[];
  /** Ids of included templates. Each must have templates/<id>.json. */
  templates?: string[];
  /** Ids of included commands. Each must have a commands/<id>.json conforming to command/v1. */
  commands?: string[];
  /** Embedded translations (subset of the workspace). Computed at export. */
  translations?: PackTranslationsMeta;
  /** Paths of included assets (relative to assets/). */
  assets?: string[];
  /** Required third-party plugins (computed at export). */
  requires_plugins?: string[];
  created_at?: string;
  updated_at?: string;
}

export interface PackTranslationsMeta {
  /** Relative path of the translations file in the archive. Default: "translations.json". */
  file?: string;
  /** Number of embedded keys (info for import dialogs). */
  key_count?: number;
  /** Languages covered by the pack's translations. */
  languages?: string[];
}

/**
 * State of a pack in the admin's workspace (backend side, outside the manifest).
 * This object is NOT part of the exported manifest — it is the tracking on the Postgres side.
 */
export interface WorkspacePack {
  /** Local id generated by the backend (UUID). */
  id: string;
  /** Id of the owning account. */
  user_id: string;
  /** Pack id as it appears in the manifest. */
  manifest_id: string;
  /** Display name. */
  name: string;
  description?: string;
  /** Current version (since the last import or create/update). */
  version: string;
  /**
   * Pack source.
   * - "user_created" : pack created locally by the admin.
   * - "imported"     : pack imported from an .itfz, can be re-imported (overwrite).
   * - "forked"       : imported pack then forked, becomes user_created but keeps a pointer to the source.
   */
  source: "user_created" | "imported" | "forked";
  /** If imported or forked, the source id (e.g. "creator-x/daily-quests"). */
  source_pack_id?: string;
  /** If imported, source version at import — useful to detect available updates. */
  source_version?: string;
  /** Default pack auto-created for each new admin (the "Personal" one). */
  is_default: boolean;
  created_at: string;
  updated_at: string;
}

